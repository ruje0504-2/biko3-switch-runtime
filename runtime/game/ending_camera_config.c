int bk_ending_camera_config(BkEndingCameraPresets *out, unsigned group,
                            unsigned variant) {
  if (!out || group >= 5 || variant >= 10)
    return 0;
  BkEndingCameraPresets next;
  for (unsigned choice = 0; choice < 3; ++choice)
    for (unsigned field = 0; field < 4; ++field)
      next.authored[field][choice] = settings[group][variant][choice][field];
  memcpy(next.active, next.authored, sizeof(next.active));
  *out = next;
  return 1;
}

